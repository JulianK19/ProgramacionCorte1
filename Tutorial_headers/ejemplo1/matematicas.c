#include "matematicas.h"

double cuadrado(double x)
{
    return x * x;                      // si x es 2, devuelve 4; si x es 3, devuelve 9; si x es 4, devuelve 16
}

double cubo(double x)
{
    return x * x * x;                  // si x es 2, devuelve 8; si x es 3, devuelve 27; si x es 4, devuelve 64
}

double promedio(double a, double b)
{
    return (a + b) / 2.0;              // si a es 2 y b es 4, devuelve 3; si a es 3 y b es 5, devuelve 4
}